/**
 * Bundle src/*.js into the single browser artifact the Harness module loader
 * expects: one `window.__ModuleLoader__.load({ id, factory })` call whose
 * factory returns { inject, apply }. The factory receives only the shared
 * module table, so the sources must stay dependency-free (no imports).
 *
 * Run with any Node: `node build.mjs`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');

const sources = ['src/match.js', 'src/plugin.js'];
const stripExports = (source) => source.replace(/^export\s+(?=(?:function|const|let|class)\b)/gm, '');
const chunks = sources.map((file) => {
  const body = stripExports(read(file)).trimEnd();
  return `/* ---- ${file} ---- */\n${body}\n`;
});

const out = `window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    /* Generated by build.mjs from src/*.js. Do not edit by hand. */
${chunks.join('\n')}
    return { inject: inject, apply: skillCnApply };
  },
});
`;

fs.writeFileSync(path.join(root, 'client.js'), out);
console.log('wrote client.js (' + Buffer.byteLength(out) + ' bytes)');
